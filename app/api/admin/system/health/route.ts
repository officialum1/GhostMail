import { NextRequest, NextResponse } from 'next/server'
import { requireAdmin } from '@/lib/admin-auth'
import { db } from '@/lib/db'
import { notifyNewEmail } from '@/lib/emailEvents'
import { getCryptoUpgradeRequests, getDeveloperApiKeys } from '@/lib/cryptoPayments'

export async function GET() {
  const authError = await requireAdmin()
  if (authError) return authError

  const startTime = Date.now()
  let dbStatus = 'healthy'
  let dbLatencyMs = 0

  try {
    const pingStart = Date.now()
    await db.$queryRaw`SELECT 1`
    dbLatencyMs = Date.now() - pingStart
  } catch {
    dbStatus = 'degraded'
    dbLatencyMs = Date.now() - startTime
  }

  try {
    const [userCount, emailCount, logCount, orders, keys] = await Promise.all([
      db.user.count().catch(() => 0),
      db.email.count().catch(() => 0),
      db.webhookLog.count().catch(() => 0),
      getCryptoUpgradeRequests().catch(() => []),
      getDeveloperApiKeys().catch(() => []),
    ])

    const mem = process.memoryUsage()

    return NextResponse.json({
      status: dbStatus === 'healthy' ? 'operational' : 'degraded',
      timestamp: new Date().toISOString(),
      uptimeSeconds: Math.floor(process.uptime()),
      database: {
        status: dbStatus,
        latencyMs: dbLatencyMs,
        provider: 'postgresql',
      },
      counts: {
        users: userCount,
        emails: emailCount,
        webhookLogs: logCount,
        cryptoOrders: orders.length,
        pendingOrders: orders.filter((o) => o.status === 'pending').length,
        developerKeys: keys.filter((k) => k.isActive).length,
      },
      runtime: {
        nodeVersion: process.version,
        platform: process.platform,
        memoryRssMb: Math.round(mem.rss / 1024 / 1024),
        memoryHeapUsedMb: Math.round(mem.heapUsed / 1024 / 1024),
      },
      webhook: {
        isSecretConfigured: Boolean(process.env.WEBHOOK_SECRET && process.env.WEBHOOK_SECRET.length >= 16),
      },
    })
  } catch (err) {
    console.error('System health check error:', err)
    return NextResponse.json({ status: 'error', error: 'Diagnostic failed' }, { status: 500 })
  }
}

/**
 * Synthetic Inbound Email Tester:
 * Simulates a realistic inbound delivery probe to verify pipeline & SSE latency.
 */
export async function POST(req: NextRequest) {
  const authError = await requireAdmin()
  if (authError) return authError

  try {
    const body = await req.json().catch(() => ({}))
    const targetEmail = (body.targetEmail || 'admin@ghostmail.store').toLowerCase().trim()
    const testType = body.testType || 'otp'

    const testStartTime = Date.now()
    const probeId = `probe_${Math.floor(100000 + Math.random() * 900000)}`
    const generatedOtp = String(Math.floor(100000 + Math.random() * 900000))

    const subject =
      testType === 'otp'
        ? `[Synthetic Probe] Your verification code is: ${generatedOtp}`
        : `[Synthetic Probe ${probeId}] System Ingestion Latency Benchmark`

    const bodyText = `This is a synthetic inbound diagnostic probe generated by the GhostMail Admin Operations Center.
Probe ID: ${probeId}
Generated OTP: ${generatedOtp}
Target Address: ${targetEmail}
Timestamp: ${new Date().toISOString()}

If this was delivered immediately, your webhook and real-time SSE stream are fully operational.`

    const user =
      (await db.user.findFirst({ where: { email: targetEmail } })) ||
      (await db.user.findFirst())

    if (!user) {
      return NextResponse.json(
        { error: 'No user exists in the database to deliver the probe to' },
        { status: 400 }
      )
    }

    const email = await db.email.create({
      data: {
        toAddress: targetEmail,
        fromAddress: 'system-probe@ghostmail.store',
        subject,
        bodyText,
        bodyHtml: `<div style="font-family:sans-serif;padding:20px;border-left:4px solid #06b6d4"><h3>GhostMail Synthetic Probe</h3><p>Your verification code is: <strong>${generatedOtp}</strong></p><p style="color:#64748b">Probe ID: ${probeId}</p></div>`,
        isRead: false,
        sent: false,
        userId: user.id,
      },
    })

    // Broadcast through live WebSocket / SSE
    notifyNewEmail(user.id)

    const latencyMs = Date.now() - testStartTime

    return NextResponse.json({
      success: true,
      probeId,
      emailId: email.id,
      targetEmail,
      otp: generatedOtp,
      latencyMs,
      message: `Synthetic probe delivered in ${latencyMs}ms!`,
    })
  } catch (err) {
    console.error('Synthetic probe delivery error:', err)
    return NextResponse.json(
      { error: err instanceof Error ? err.message : 'Probe delivery failed' },
      { status: 500 }
    )
  }
}
